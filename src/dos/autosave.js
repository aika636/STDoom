// Сохранение прогресса по факту сохранения в игре (план §4.10).
//
// ЗАЧЕМ ЭТО ЕСТЬ. `persist()` зовётся по закрытию окна и по уходу со вкладки, и оба
// раза — из `dos/session.js`. Есть третий выход, который этими двумя не закрывается:
// игрок выходит из DOOM его собственным меню (F10 → y). Эмулятор тогда завершается
// сам, `runtime.js` поднимает флаг `exited`, и `persist()` после этого уже не трогает
// мёртвый эмулятор — сейвы, сделанные за сессию, не доезжают до IndexedDB МОЛЧА.
// Это ровно тот класс отказа, что описан в §4.10, только другим путём.
//
// Лечение выбрано событийное, а не таймерное: §4.10 прямо запрещает автосохранение по
// таймеру («persist() не бесплатен»), и справедливо — крутить сериализацию файловой
// системы вслепую незачем. Но момент, когда прогресс ПОЯВЛЯЕТСЯ, известен точно: это
// сохранение внутри игры. F2 — «Save Game», F6 — быстрое сохранение; обе клавиши в
// ванильном DOOM зашиты в движок и на раскладку из §5.2 не завязаны.
//
// ПОЧЕМУ НЕ СРАЗУ ПО F2. F2 только ОТКРЫВАЕТ меню сохранения: дальше игрок выбирает
// слот стрелками, набирает имя и жмёт Enter — файл пишется в конце этой цепочки, и
// `persist()` по самой F2 унёс бы в базу состояние ДО записи. Поэтому клавиша не
// сохраняет, а взводит: сохранение уходит через паузу тишины после последнего нажатия
// (`QUIET_MS`), а чтобы взведённое состояние не висело вечно, если игрок после F2 не
// отпускает клавиши, стоит потолок от момента взвода (`MAX_MS`).
//
// Ложное срабатывание здесь дёшево (лишний `persist()` раз в сессию сохранения), а
// пропуск — дорог (потерянный прогресс), поэтому пороги выбраны в сторону «лучше
// сохранить лишний раз».

import { logWarn } from '../log.js';

/** Клавиши сохранения ванильного DOOM. Это `event.code`, не скан-коды. */
export const SAVE_KEYS = new Set(['F2', 'F6']);

/**
 * Клавиша выхода из игры. F10 в ванильном DOOM открывает «Quit Game? (y/n)», и это
 * последний момент, когда эмулятор ещё жив.
 *
 * ЗАЧЕМ ОНА ЗДЕСЬ. Дыра ровно в том сценарии, ради которого модуль и написан:
 * игрок сохранился (F6) и в ближайшую секунду решил выйти (F10 → y). F10 и y —
 * клавиши не-сохранения, а они ПРОДЛЕВАЮТ паузу тишины: DOOM успевает завершиться
 * раньше, чем сработает таймер, `onExit` снимает взвод, и прогресс теряется молча.
 * Продление тут работает против себя — чем больше игрок нажимает, тем позже пишем.
 *
 * Поэтому F10 не продлевает ожидание, а обрывает его: сохраняем немедленно, пока
 * `ci` ещё отвечает. Ложное срабатывание здесь по-прежнему дёшево — лишний
 * `persist()` на выходе из игры, — а пропуск по-прежнему дорог.
 */
export const QUIT_KEY = 'F10';

/** Тишина после последнего нажатия, после которой считаем, что запись состоялась. */
export const QUIET_MS = 1500;

/** Потолок от взвода: дальше ждать бессмысленно, сохраняем как есть. */
export const MAX_MS = 10000;

/**
 * @param {object} params
 * @param {() => Promise<boolean>|boolean} params.persist что звать по срабатыванию
 * @param {(fn: () => void, ms: number) => any} [params.setTimer] для тестов
 * @param {(id: any) => void} [params.clearTimer] для тестов
 * @param {() => number} [params.now] для тестов
 */
export function createAutosave({
    persist,
    setTimer = setTimeout,
    clearTimer = clearTimeout,
    now = () => Date.now(),
} = {}) {
    let timer = null;
    // Взвод — отдельным флагом, а не «armedAt !== 0»: часы имеют полное право
    // показывать ноль (свой источник времени в тестах, performance.now() в начале
    // страницы), и взвод в этот момент читался бы как его отсутствие.
    let armed = false;
    let armedAt = 0;
    let saves = 0;

    function clear() {
        if (timer !== null) clearTimer(timer);
        timer = null;
    }

    function fire() {
        if (!armed) return;
        clear();
        armed = false;
        saves++;
        try {
            // Результат намеренно не ждём: автосохранение не должно ни задерживать
            // ввод, ни тем более ронять его своей ошибкой. Отказ persist() внутри
            // себя уже логирует (runtime.js), здесь ловим только синхронный срыв.
            Promise.resolve(persist()).catch((err) => logWarn('автосохранение не удалось', err));
        } catch (err) {
            logWarn('автосохранение не удалось', err);
        }
    }

    function schedule() {
        clear();
        // Ждём тишину, но не дольше потолка от момента взвода — иначе непрерывный
        // ввод откладывал бы сохранение бесконечно.
        const left = Math.max(0, MAX_MS - (now() - armedAt));
        timer = setTimer(fire, Math.min(QUIET_MS, left));
    }

    return {
        /**
         * Нажата клавиша. `code` — `event.code`. Клавиша сохранения взводит таймер,
         * любая другая продлевает тишину, но только пока мы взведены: в обычной игре
         * ничего не планируется вовсе.
         */
        noteKey(code) {
            if (SAVE_KEYS.has(code)) {
                if (!armed) {
                    armed = true;
                    armedAt = now();
                }
                schedule();
            } else if (code === QUIT_KEY) {
                // Ждать больше нечего и некогда: эмулятор вот-вот завершится (см.
                // QUIT_KEY). Если взвода не было, fire() сам ничего не делает.
                fire();
            } else if (armed) {
                schedule();
            }
        },
        /** Сохранить немедленно, если взведены. Нужно на уходе со вкладки и в уборке. */
        flush() { fire(); },
        /** Снять взвод без сохранения: сессия уже гасится своим `persist()`. */
        cancel() {
            clear();
            armed = false;
        },
        get armed() { return armed; },
        get saves() { return saves; },
    };
}
